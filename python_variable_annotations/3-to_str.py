#!/usr/bin/env python3
"""
Module providing a type‑annotated function that converts a float to a string.
This module contains a function that returns the string representation of a
floating‑point number.
"""


def to_str(n: float) -> str:
    """
    Return the string representation of a floating‑point number.

    Args:
        n (float): The number to convert.

    Returns:
        str: The string representation of n.
    """
    return str(n)
